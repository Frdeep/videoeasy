const SUPABASE_HOST = /\.supabase\.(co|com)$/i;
const SSL_PARAMS = [
  "sslmode",
  "ssl",
  "sslcert",
  "sslkey",
  "sslrootcert",
  "uselibpqcompat",
];

/**
 * Builds pg pool settings. For Supabase hosts (direct or Session pooler), TLS
 * is enforced with certificate AND hostname verification against the Supabase
 * root CA. SSL query parameters are removed because pg lets them override the
 * explicit `ssl` option. Other hosts (local/CI databases) are left untouched.
 */
export function poolConfig(connectionString: string): PoolConfig {
  let url: URL;
  try {
    url = new URL(connectionString);
  } catch {
    return { connectionString };
  }
  if (!SUPABASE_HOST.test(url.hostname)) return { connectionString };
  for (const p of SSL_PARAMS) url.searchParams.delete(p);
  return {
    connectionString: url.toString(),
    ssl: { ca: SUPABASE_ROOT_CA, rejectUnauthorized: true },
  };
}

/** Error code safe to log: pg SQLSTATE or Node errno, never a message. */
export function safeErrorCode(error: unknown): string {
  const code = (error as { code?: unknown } | null)?.code;
  return typeof code === "string" && /^[A-Z0-9_]{2,40}$/.test(code)
    ? code
    : "UNKNOWN";
}
